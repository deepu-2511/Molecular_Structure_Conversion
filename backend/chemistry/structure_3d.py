from pathlib import Path

from rdkit import Chem
from rdkit.Chem import AllChem


class Structure3DEngine:
    """3D molecular structure generation and export engine."""

    @staticmethod
    def generate_conformer(
        molecule,
        optimize=True,
        random_seed=42
    ):
        """
        Generate a 3D conformer using ETKDG and optionally
        optimize geometry using MMFF or UFF.
        """

        mol = Chem.AddHs(Chem.Mol(molecule))

        parameters = AllChem.ETKDGv3()
        parameters.randomSeed = random_seed

        result = AllChem.EmbedMolecule(
            mol,
            parameters
        )

        if result != 0:
            raise ValueError(
                "3D conformer generation failed."
            )

        optimization_method = "none"

        if optimize:
            mmff_result = AllChem.MMFFOptimizeMolecule(mol)

            if mmff_result == 0:
                optimization_method = "MMFF"
            else:
                uff_result = AllChem.UFFOptimizeMolecule(mol)

                if uff_result == 0:
                    optimization_method = "UFF"
                else:
                    optimization_method = "unoptimized"

        return mol, optimization_method

    @staticmethod
    def get_energy(molecule):
        """Calculate the MMFF molecular energy."""

        properties = AllChem.MMFFGetMoleculeProperties(molecule)

        if properties is None:
            return None

        force_field = AllChem.MMFFGetMoleculeForceField(
            molecule,
            properties
        )

        if force_field is None:
            return None

        return round(force_field.CalcEnergy(), 6)

    @staticmethod
    def export_sdf(molecule, output_path):
        """Export 3D molecule as SDF."""

        output_path = Path(output_path)
        output_path.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        writer = Chem.SDWriter(str(output_path))
        writer.write(molecule)
        writer.close()

        return output_path

    @staticmethod
    def export_mol(molecule, output_path):
        """Export molecule as MOL."""

        output_path = Path(output_path)
        output_path.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        Chem.MolToMolFile(
            molecule,
            str(output_path)
        )

        return output_path

    @staticmethod
    def export_pdb(molecule, output_path):
        """Export molecule as PDB."""

        output_path = Path(output_path)
        output_path.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        Chem.MolToPDBFile(
            molecule,
            str(output_path)
        )

        return output_path

    @staticmethod
    def export_xyz(molecule, output_path):
        """Export molecule as XYZ."""

        output_path = Path(output_path)
        output_path.parent.mkdir(
            parents=True,
            exist_ok=True
        )

        conformer = molecule.GetConformer()

        atoms = molecule.GetAtoms()

        lines = [
            str(molecule.GetNumAtoms()),
            "Generated by MolecularStructureAI"
        ]

        for atom in atoms:
            position = conformer.GetAtomPosition(
                atom.GetIdx()
            )

            lines.append(
                f"{atom.GetSymbol()} "
                f"{position.x:.6f} "
                f"{position.y:.6f} "
                f"{position.z:.6f}"
            )

        output_path.write_text(
            "\n".join(lines),
            encoding="utf-8"
        )

        return output_path

    @classmethod
    def generate_3d(cls, molecule):
        """Generate and analyze a 3D molecular structure."""

        mol_3d, method = cls.generate_conformer(
            molecule
        )

        energy = cls.get_energy(mol_3d)

        return {
            "molecule": mol_3d,
            "optimization_method": method,
            "energy": energy,
            "atom_count": mol_3d.GetNumAtoms(),
            "conformer_count": mol_3d.GetNumConformers(),
        }